# WATCHDOG SPATIAL AUDITOR ENGINE
# ==============================================================================
class GISZoningAuditor:
    """
    Evaluates Planning Cases and Permit Requests against spatial zoning boundaries.
    """
    @staticmethod
    def is_within_skid_row(lat, lon):
        within_lat = SKID_ROW_BOUNDS['lat_south'] <= lat <= SKID_ROW_BOUNDS['lat_north']
        within_lon = SKID_ROW_BOUNDS['lon_west'] <= lon <= SKID_ROW_BOUNDS['lon_east']
        return within_lat and within_lon

    @classmethod
    def audit_case(cls, case):
        lat = float(case.get("latitude", 0))
        lon = float(case.get("longitude", 0))
        proposed_units = int(case.get("total_proposed_units", 0))
        affordable_units = int(case.get("affordable_units_covenanted", 0))
        zoning = case.get("zoning_requested", "")
        project_name = case.get("project_name", "Unknown Case")

        is_inside = cls.is_within_skid_row(lat, lon)
        aff_rate = (affordable_units / proposed_units * 100) if proposed_units > 0 else 0.0
        
        audit_result = {
            "case_number": case.get("case_number", "N/A"),
            "project": project_name,
            "address": case.get("street_address", "Unknown Address"),
            "coordinates": (lat, lon),
            "inside_skid_row": is_inside,
            "affordability_rate": round(aff_rate, 2),
            "zoning_compliance": "PASS",
            "warnings": [],
            "severity": "INFO"
        }

        # Case 1: Proposal sits directly inside historical Skid Row boundaries
        if is_inside:
            # IX1 represents the critical Affordable Housing Only mandate (demanding 80% covenanted units)
            if "IX1" in zoning or "IX1" in case.get("status", ""):
                if aff_rate < 80.0:
                    audit_result["zoning_compliance"] = "CRITICAL VIOLATION"
                    audit_result["warnings"].append("IX1 Zone requires minimum 80% covenanted low-income housing!")
                    audit_result["severity"] = "CRITICAL"
            else:
                # General residential or commercial requests inside boundary must support at least 20% affordability
                if proposed_units > 0 and aff_rate < 20.0:
                    audit_result["zoning_compliance"] = "WARNING"
                    audit_result["warnings"].append("Low affordability rate inside Skid Row boundaries is a gentrification trigger.")
                    audit_result["severity"] = "WARNING"
            
            # Check for compatible-use perimeter restrictions (such as alcohol conditional use permits)
            if "CUB" in case.get("case_number", "") or "conditional-use" in zoning.lower():
                audit_result["zoning_compliance"] = "COMPATIBLE USE EXCLUSION"
                audit_result["warnings"].append("Conditional Use Permit (CUB/Alcohol/Dispensary) detected. Restrictive covenants apply near recovery spaces.")
                audit_result["severity"] = "WARNING"

        # Case 2: Sits in the surrounding border zone (edge buffer check)
        else:
            is_near_boundary = (
                abs(lat - SKID_ROW_BOUNDS['lat_north']) < BUFFER_DISTANCE_DEG or
                abs(lat - SKID_ROW_BOUNDS['lat_south']) < BUFFER_DISTANCE_DEG or
                abs(lon - SKID_ROW_BOUNDS['lon_west']) < BUFFER_DISTANCE_DEG or
                abs(lon - SKID_ROW_BOUNDS['lon_east']) < BUFFER_DISTANCE_DEG
            )
            if is_near_boundary:
                # Perimeter buffer builds require minimum 15% affordable set-asides to prevent outward displacement pressure
                if proposed_units > 0 and aff_rate < 15.0:
                    audit_result["zoning_compliance"] = "BUFFER INVASION"
                    audit_result["warnings"].append("Speculative pressure alert! Luxury build on Skid Row perimeter threatens buffer stability.")
                    audit_result["severity"] = "WARNING"
                
                # Highlight the $2B Fourth & Central case specifically
                if "Fourth & Central" in project_name and aff_rate <= 15.63:
                    audit_result["zoning_compliance"] = "BUFFER WATCH"
                    audit_result["warnings"].append("Border monitoring active. $2B Fourth & Central project requires 1:1 SRO protection safeguards.")
                    audit_result["severity"] = "WARNING"

        return audit_result

