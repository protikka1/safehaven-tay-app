# TRACK C: PROSOCIAL CIVIC TRUST PORTAL (NLP SoM MITIGATOR)
# ==============================================================================
class ProsocialCivicTrustPortal:
    """
    Mitigates the 'Sense of Misinformation' (SoM) by detecting highly-polarized,
    unsubstantiated claims, providing local public policy facts, and offering
    prosocial paraphrasing alternatives to support community-wide dialogue.
    """
    SOM_TRIGGERS = [
        (r"\b(bribed|corruption|crooks?|shady|bribery)\b", 
         "DTLA 2040 was marked by high transparency inside the Planning Commission, though amendments require careful statutory verification. Let's focus on auditing specific planning requests rather than declaring bad intent."),
        (r"\b(demolish everything|kick out everyone|gentrifying our entire community)\b", 
         "The Downtown Community Plan (DTLA 2040) actually doubles the area where permanent supportive and affordable housing is permitted (expanding from 33% to 60%). Let's map coordinates to ensure individual SROs are protected under the 1:1 replacement ordinance.")
    ]

    @classmethod
    def evaluate_and_paraphrase(cls, user_text):
        """
        Analyzes post text, detects SoM risks, and constructs positive alternatives.
        """
        som_detected = False
        warnings = []
        factual_groundings = []

        for pattern, response in cls.SOM_TRIGGERS:
            if re.search(pattern, user_text, re.IGNORECASE):
                som_detected = True
                warnings.append(f"Polarizing language detected targeting: '{re.search(pattern, user_text, re.IGNORECASE).group(0)}'")
                factual_groundings.append(response)

        if not som_detected:
            return {
                "som_detected": False,
                "moderated_text": user_text,
                "factual_groundings": [],
                "warnings": []
            }

        # Dynamic prosocial re-write engine
        moderated_text = user_text
        # Clean up hostile/unsubstantiated claims with constructive demand framing
        moderated_text = re.sub(r"\b(bribed|crooks?|corruption)\b", "unregulated administrative variances", moderated_text, flags=re.IGNORECASE)
        moderated_text = re.sub(r"\b(kick out everyone|demolish everything)\b", "reduce our historical affordable SRO housing stock", moderated_text, flags=re.IGNORECASE)
        
        # Append policy demand
        moderated_text += "\n\nProposed Action: We urge the City Council to fully expand the IX1 (Affordable Housing Only) zone across all historical Skid Row boundaries to ensure covenanted protections."

        return {
            "som_detected": True,
            "original_text": user_text,
            "moderated_text": moderated_text,
            "factual_groundings": factual_groundings,
            "warnings": warnings
        }


