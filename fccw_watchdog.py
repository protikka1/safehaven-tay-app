# TRACK A: GIS ZONING AUDIT ENGINE (SPATIAL AUDITOR)
# ==============================================================================
class ZoningAuditEngine:
    """
    Simulates a Geographic Information System (GIS) coordinate auditor.
    Skid Row boundaries are established as:
      - North: 3rd Street (lat: 34.0482)
      - South: 7th Street (lat: 34.0410)
      - West: Main Street (lon: -118.2495)
      - East: Alameda Avenue (lon: -118.2360)
    """
    SKID_ROW_BOUNDS = {
        'lat_north': 34.0482,
        'lat_south': 34.0410,
        'lon_west': -118.2495,
        'lon_east': -118.2360
    }

    @classmethod
    def is_within_skid_row(cls, lat, lon):
        within_lat = cls.SKID_ROW_BOUNDS['lat_south'] <= lat <= cls.SKID_ROW_BOUNDS['lat_north']
        within_lon = cls.SKID_ROW_BOUNDS['lon_west'] <= lon <= cls.SKID_ROW_BOUNDS['lon_east']
        return within_lat and within_lon

    @classmethod
    def audit_development_proposal(cls, project_name, lat, lon, proposed_units, affordable_units, zoning_requested):
        """
        Evaluates proposed zoning against Skid Row's protective IX1 (Affordable Housing Only) boundary.
        """
        is_in_skid_row = cls.is_within_skid_row(lat, lon)
        affordability_ratio = (affordable_units / proposed_units) if proposed_units > 0 else 0
        
        status = {
            "project": project_name,
            "coordinates": (lat, lon),
            "inside_skid_row": is_in_skid_row,
            "affordability_rate": round(affordability_ratio * 100, 2),
            "zoning_compliance": "PASS",
            "warnings": [],
            "severity": "INFO"
        }

        if is_in_skid_row:
            # IX1 Zone demands maximum affordable protection (Inclusionary mandates)
            if zoning_requested in ["IX1", "IX2", "IX4"] or zoning_requested.startswith("R"):
                if affordability_ratio < 0.80 and zoning_requested == "IX1":
                    status["zoning_compliance"] = "CRITICAL VIOLATION"
                    status["warnings"].append("IX1 Zone requires minimum 80% covenanted low-income housing!")
                    status["severity"] = "CRITICAL"
                elif affordability_ratio < 0.20:
                    status["zoning_compliance"] = "WARNING"
                    status["warnings"].append("Low affordability rate inside Skid Row boundaries is a gentrification trigger.")
                    status["severity"] = "WARNING"
                    
            if zoning_requested in ["IX2", "IX4"] and proposed_units > 500:
                status["warnings"].append("Excessive square footage/density in commercial buffers; adaptive reuse caps might be exceeded.")
                if status["severity"] != "CRITICAL":
                    status["severity"] = "WARNING"
        else:
            # Project is outside Skid Row, but check if it's on the boundary (Buffer Zone check)
            # A projects within 0.005 degrees of Skid Row bounds is considered on the "Strong Edge" buffer
            buffer_dist = 0.005
            is_near_boundary = (
                abs(lat - cls.SKID_ROW_BOUNDS['lat_north']) < buffer_dist or
                abs(lat - cls.SKID_ROW_BOUNDS['lat_south']) < buffer_dist or
                abs(lon - cls.SKID_ROW_BOUNDS['lon_west']) < buffer_dist or
                abs(lon - cls.SKID_ROW_BOUNDS['lon_east']) < buffer_dist
            )
            if is_near_boundary and affordability_ratio < 0.15:
                status["zoning_compliance"] = "BUFFER INVASION"
                status["warnings"].append("Speculative pressure alert! Luxury build on Skid Row perimeter threatens buffer stability.")
                status["severity"] = "WARNING"

        return status

