# TRACK B: SRO 1:1 REPLACEMENT LEDGER (DATABASE ENGINE)
# ==============================================================================
class SROLedgerEngine:
    """
    Manages a relational database tracing SRO unit inventories and auditing
    redevelopment permits against active 1:1 replacement covenants.
    """
    def __init__(self, db_path=":memory:"):
        self.conn = sqlite3.connect(db_path)
        self.conn.row_factory = sqlite3.Row
        self._initialize_database()

    def _initialize_database(self):
        cursor = self.conn.cursor()
        # Enable Foreign Keys
        cursor.execute("PRAGMA foreign_keys = ON;")
        
        # SRO Hotel registry
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS sro_hotels (
                id TEXT PRIMARY KEY,
                name TEXT NOT NULL,
                street_address TEXT NOT NULL,
                total_historic_units INTEGER NOT NULL,
                current_active_units INTEGER NOT NULL,
                operator_nonprofit TEXT
            );
        """)
        
        # Replacement Covenants Track
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS replacement_covenants (
                id TEXT PRIMARY KEY,
                redevelopment_project TEXT NOT NULL,
                original_hotel_id TEXT REFERENCES sro_hotels(id),
                units_demolished INTEGER NOT NULL,
                replacement_units_covenanted INTEGER NOT NULL,
                replacement_site_address TEXT NOT NULL,
                covenant_status TEXT CHECK(covenant_status IN ('Pending', 'Certified', 'Violated')),
                recorded_date TEXT DEFAULT CURRENT_TIMESTAMP
            );
        """)
        self.conn.commit()

    def seed_initial_sro_data(self):
        cursor = self.conn.cursor()
        sro_data = [
            ("renato-01", "Renato Apartments SRO", "538 S San Julian St", 100, 100, "SRO Housing Corp"),
            ("baltimore-02", "Baltimore Hotel", "501 S Los Angeles St", 150, 150, "AIDS Healthcare Foundation"),
            ("king-edward-03", "King Edward Hotel", "121 E 5th St", 120, 120, "AIDS Healthcare Foundation"),
            ("madison-04", "Madison Hotel", "423 E 7th St", 200, 200, "Healthy Housing Foundation"),
            ("rosslyn-05", "Rosslyn Hotel Annex", "451 S Main St", 264, 264, "SRO Housing Corp")
        ]
        cursor.executemany("""
            INSERT OR IGNORE INTO sro_hotels (id, name, street_address, total_historic_units, current_active_units, operator_nonprofit)
            VALUES (?, ?, ?, ?, ?, ?);
        """, sro_data)
        self.conn.commit()

    def register_demolition_and_replacement(self, OriginalHotelId, RedevelopmentProject, UnitsDemolished, ReplacementUnits, ReplacementSiteAddress):
        """
        Enforces the 1:1 Replacement Rule. If ReplacementUnits < UnitsDemolished, the transaction fails audit.
        """
        cursor = self.conn.cursor()
        
        # Fetch SRO Hotel
        cursor.execute("SELECT name, current_active_units FROM sro_hotels WHERE id = ?;", (OriginalHotelId,))
        hotel = cursor.fetchone()
        if not hotel:
            return {"status": "FAILED", "message": f"SRO Hotel with ID '{OriginalHotelId}' not found in registry."}

        # Check if 1:1 rule is violated mathematically
        rule_violation = ReplacementUnits < UnitsDemolished
        covenant_status = "Violated" if rule_violation else "Certified"
        
        cov_id = f"COV-{uuid_mock()}"
        
        try:
            # 1. Update SRO Active count
            new_active_count = max(0, hotel['current_active_units'] - UnitsDemolished)
            cursor.execute("UPDATE sro_hotels SET current_active_units = ? WHERE id = ?;", (new_active_count, OriginalHotelId))
            
            # 2. Insert Covenant Entry
            cursor.execute("""
                INSERT INTO replacement_covenants (id, redevelopment_project, original_hotel_id, units_demolished, replacement_units_covenanted, replacement_site_address, covenant_status)
                VALUES (?, ?, ?, ?, ?, ?, ?);
            """, (cov_id, RedevelopmentProject, OriginalHotelId, UnitsDemolished, ReplacementUnits, ReplacementSiteAddress, covenant_status))
            
            self.conn.commit()
            
            if rule_violation:
                return {
                    "status": "VIOLATION",
                    "covenant_id": cov_id,
                    "message": f"CRITICAL: 1:1 replacement rule violated for '{RedevelopmentProject}'! Demolished {UnitsDemolished} SRO units but only covenanted {ReplacementUnits} replacement units."
                }
            else:
                return {
                    "status": "APPROVED",
                    "covenant_id": cov_id,
                    "message": f"Certified: 1:1 replacement covenant validated for '{RedevelopmentProject}'. {UnitsDemolished} SRO units replaced."
                }
        except Exception as e:
            self.conn.rollback()
            return {"status": "FAILED", "message": f"Transaction rolled back: {e}"}

    def fetch_audit_summary(self):
        cursor = self.conn.cursor()
        cursor.execute("""
            SELECT c.id as covenant, c.redevelopment_project, h.name as original_hotel,
                   c.units_demolished, c.replacement_units_covenanted, c.covenant_status
            FROM replacement_covenants c
            JOIN sro_hotels h ON c.original_hotel_id = h.id;
        """)
        return [dict(row) for row in cursor.fetchall()]

