@dataclass(frozen=True)
class ProjectAudit:
    status: str
    reason: str


def audit_project(
    latitude: float,
    longitude: float,
    affordable_percent: float,
) -> ProjectAudit:
    """Classify a project against the monitored Skid Row thresholds."""
    bounds = ZoningAuditEngine.SKID_ROW_BOUNDS
    inside = (
        bounds["lat_south"] <= latitude <= bounds["lat_north"]
        and bounds["lon_west"] <= longitude <= bounds["lon_east"]
    )
    if inside and affordable_percent < 80:
        return ProjectAudit(
            "CRITICAL VIOLATION",
            "Inside IX1 boundary below 80% affordability",
        )
    if affordable_percent < 15:
        return ProjectAudit(
            "BUFFER WATCH",
            "Below 15% affordability near the monitored boundary",
        )
    if inside:
        return ProjectAudit(
            "PASS",
            "Inside monitored boundary and meets the 80% threshold",
        )
    return ProjectAudit("OUTSIDE SCOPE", "Project is outside the monitored boundary")


def replacement_ledger_status(units_lost: int, covenanted_units: int) -> ProjectAudit:
    """Check the SRO one-for-one replacement requirement."""
    if units_lost < 0 or covenanted_units < 0:
        raise ValueError("Unit counts cannot be negative")
    if covenanted_units < units_lost:
        return ProjectAudit(
            "CRITICAL VIOLATION",
            "Replacement units do not meet the 1:1 requirement",
        )
    return ProjectAudit(
        "PASS",
        "Replacement units meet or exceed the 1:1 requirement",
    )

