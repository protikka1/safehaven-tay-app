class SROLedgerEngine:
    """
    Manages a relational database tracing SRO unit inventories and auditing
    redevelopment permits against active 1:1 replacement covenants.
    """
    def __init__(self, db_path=DEFAULT_DB_PATH):
        self.conn = sqlite3.connect(db_path)
        self.conn.row_factory = sqlite3.Row
        self._initialize_database()

    def _initialize_database(self):
        cursor = self.conn.cursor()
        # Enable Foreign Keys
        cursor.execute("PRAGMA foreign_keys = ON;")
        
        # SRO Hotel registry
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS sro_hotels (
                id TEXT PRIMARY KEY,
                name TEXT NOT NULL,
                street_address TEXT NOT NULL,
                total_historic_units INTEGER NOT NULL,
                current_active_units INTEGER NOT NULL,
                operator_nonprofit TEXT
            );
        """)
        
        # Replacement Covenants Track
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS replacement_covenants (
                id TEXT PRIMARY KEY,
                redevelopment_project TEXT NOT NULL,
                original_hotel_id TEXT REFERENCES sro_hotels(id),
                units_demolished INTEGER NOT NULL,
                replacement_units_covenanted INTEGER NOT NULL,
                replacement_site_address TEXT NOT NULL,
                covenant_status TEXT CHECK(covenant_status IN ('Pending', 'Certified', 'Violated')),
                recorded_date TEXT DEFAULT CURRENT_TIMESTAMP
            );
        """)
        cursor.executescript("""
            CREATE TABLE IF NOT EXISTS sro_ledger (
                id TEXT PRIMARY KEY,
                case_ref TEXT NOT NULL,
                units_lost INTEGER NOT NULL DEFAULT 0,
                units_replaced INTEGER NOT NULL DEFAULT 0,
                net_delta INTEGER NOT NULL DEFAULT 0,
                notes TEXT,
                created_at TEXT DEFAULT CURRENT_TIMESTAMP
            );
            CREATE TABLE IF NOT EXISTS gis_live_feeds (
                id TEXT PRIMARY KEY,
                feed_source TEXT NOT NULL,
                external_case_id TEXT UNIQUE NOT NULL,
                project_name TEXT NOT NULL,
                latitude REAL NOT NULL,
                longitude REAL NOT NULL,
                proposed_units INTEGER DEFAULT 0,
                affordable_units INTEGER DEFAULT 0,
                zoning_requested TEXT,
                audit_status TEXT NOT NULL,
                audit_warnings TEXT,
                verification_status TEXT NOT NULL DEFAULT 'PENDING_REVIEW'
                    CHECK (verification_status IN ('PENDING_REVIEW', 'VERIFIED', 'DISMISSED')),
                verified_by TEXT,
                verification_notes TEXT,
                verified_at TEXT,
                ingested_at TEXT DEFAULT CURRENT_TIMESTAMP
            );
            CREATE INDEX IF NOT EXISTS idx_gis_verification_status
                ON gis_live_feeds (verification_status);
        """)
        with self.conn:
            self.conn.execute("BEGIN IMMEDIATE")
            columns = {row["name"] for row in self.conn.execute("PRAGMA table_info(gis_live_feeds)")}
            if "source_details" not in columns:
                self.conn.execute("ALTER TABLE gis_live_feeds ADD COLUMN source_details TEXT")
            self.conn.execute("""
                CREATE TABLE IF NOT EXISTS gis_feed_sync (
                    feed_source TEXT PRIMARY KEY,
                    last_success_at TEXT NOT NULL
                )
            """)

    def upsert_gis_feed_record(
        self, *, feed_source, external_case_id, project_name, latitude, longitude,
        proposed_units=0, affordable_units=0, zoning_requested=None, source_details=None,
    ):
        """Audit one source record and reopen review only when its contents change."""
        if not -90 <= latitude <= 90 or not -180 <= longitude <= 180:
            raise ValueError("Coordinates are out of range.")
        if not 0 <= affordable_units <= proposed_units:
            raise ValueError("Unit counts are inconsistent.")
        if not all(value.strip() for value in (feed_source, external_case_id, project_name)):
            raise ValueError("Source, case ID and project name are required.")
        audit = ZoningAuditEngine.audit_development_proposal(
            project_name, latitude, longitude, proposed_units, affordable_units,
            zoning_requested or "",
        )
        if feed_source == "LADBS":
            audit = {
                "zoning_compliance": "NOT ASSESSED",
                "warnings": ["Permit data does not establish affordability or SRO replacement obligations."],
            }
        fields = {
            "project_name": project_name,
            "latitude": latitude,
            "longitude": longitude,
            "proposed_units": proposed_units,
            "affordable_units": affordable_units,
            "zoning_requested": zoning_requested,
            "audit_status": audit["zoning_compliance"],
            "audit_warnings": json.dumps(audit["warnings"]),
            "source_details": json.dumps(source_details, sort_keys=True) if source_details else None,
        }
        owns_transaction = not self.conn.in_transaction
        with self.conn if owns_transaction else nullcontext():
            if owns_transaction:
                self.conn.execute("BEGIN IMMEDIATE")
            existing = self.conn.execute(
                "SELECT * FROM gis_live_feeds WHERE external_case_id = ?", (external_case_id,)
            ).fetchone()
            if existing is None:
                self.conn.execute(
                    f"""INSERT INTO gis_live_feeds
                        (id, feed_source, external_case_id, {", ".join(fields)})
                        VALUES (?, ?, ?, {", ".join("?" for _ in fields)})""",
                    (str(uuid4()), feed_source, external_case_id, *fields.values()),
                )
            elif existing["feed_source"] != feed_source:
                raise ValueError("This case ID is already registered under a different source.")
            elif any(existing[key] != value for key, value in fields.items()):
                assignments = ", ".join(f"{key} = ?" for key in fields)
                self.conn.execute(
                    f"""UPDATE gis_live_feeds SET {assignments},
                        verification_status = 'PENDING_REVIEW', verified_by = NULL,
                        verification_notes = NULL, verified_at = NULL,
                        ingested_at = CURRENT_TIMESTAMP WHERE id = ?""",
                    (*fields.values(), existing["id"]),
                )
            return dict(self.conn.execute(
                "SELECT * FROM gis_live_feeds WHERE external_case_id = ?", (external_case_id,)
            ).fetchone())

    def mark_feed_success(self, feed_source):
        with self.conn if not self.conn.in_transaction else nullcontext():
            self.conn.execute("""
                INSERT INTO gis_feed_sync (feed_source, last_success_at)
                VALUES (?, strftime('%Y-%m-%dT%H:%M:%SZ', 'now'))
                ON CONFLICT(feed_source) DO UPDATE SET last_success_at = excluded.last_success_at
            """, (feed_source,))

    def feed_last_success(self, feed_source):
        row = self.conn.execute(
            "SELECT last_success_at FROM gis_feed_sync WHERE feed_source = ?", (feed_source,)
        ).fetchone()
        return row["last_success_at"] if row else None

    def list_gis_records(self, status=None):
        if status is None:
            rows = self.conn.execute("SELECT * FROM gis_live_feeds ORDER BY ingested_at DESC, id")
        else:
            rows = self.conn.execute(
                """SELECT * FROM gis_live_feeds WHERE verification_status = ?
                   ORDER BY ingested_at DESC, id""", (status,)
            )
        return [dict(row) for row in rows]

    def verify_gis_record(self, record_id, reviewer, status="VERIFIED", notes=None):
        if status not in ("VERIFIED", "DISMISSED") or not reviewer.strip():
            raise ValueError("Provide a reviewer and a VERIFIED or DISMISSED decision.")
        with self.conn if not self.conn.in_transaction else nullcontext():
            row = self.conn.execute(
                """UPDATE gis_live_feeds SET verification_status = ?, verified_by = ?,
                   verification_notes = ?, verified_at = CURRENT_TIMESTAMP
                   WHERE id = ? RETURNING *""", (status, reviewer, notes, record_id)
            ).fetchone()
            if row is None:
                raise ValueError(f"Unknown record UUID: {record_id}")
            return dict(row)


    def seed_initial_sro_data(self):
        cursor = self.conn.cursor()
        sro_data = [
            ("renato-01", "Renato Apartments SRO", "538 S San Julian St", 100, 100, "SRO Housing Corp"),
            ("baltimore-02", "Baltimore Hotel", "501 S Los Angeles St", 150, 150, "AIDS Healthcare Foundation"),
            ("king-edward-03", "King Edward Hotel", "121 E 5th St", 120, 120, "AIDS Healthcare Foundation"),
            ("madison-04", "Madison Hotel", "423 E 7th St", 200, 200, "Healthy Housing Foundation"),
            ("rosslyn-05", "Rosslyn Hotel Annex", "451 S Main St", 264, 264, "SRO Housing Corp")
        ]
        cursor.executemany("""
            INSERT OR IGNORE INTO sro_hotels (id, name, street_address, total_historic_units, current_active_units, operator_nonprofit)
            VALUES (?, ?, ?, ?, ?, ?);
        """, sro_data)
        self.conn.commit()

    def register_demolition_and_replacement(self, OriginalHotelId, RedevelopmentProject, UnitsDemolished, ReplacementUnits, ReplacementSiteAddress):
        """
        Enforces the 1:1 Replacement Rule. If ReplacementUnits < UnitsDemolished, the transaction fails audit.
        """
        cursor = self.conn.cursor()
        
        # Fetch SRO Hotel
        cursor.execute("SELECT name, current_active_units FROM sro_hotels WHERE id = ?;", (OriginalHotelId,))
        hotel = cursor.fetchone()
        if not hotel:
            return {"status": "FAILED", "message": f"SRO Hotel with ID '{OriginalHotelId}' not found in registry."}

        # Check if 1:1 rule is violated mathematically
        rule_violation = ReplacementUnits < UnitsDemolished
        covenant_status = "Violated" if rule_violation else "Certified"
        
        cov_id = f"COV-{uuid4()}"
        
        try:
            # 1. Update SRO Active count
            new_active_count = max(0, hotel['current_active_units'] - UnitsDemolished)
            cursor.execute("UPDATE sro_hotels SET current_active_units = ? WHERE id = ?;", (new_active_count, OriginalHotelId))
            
            # 2. Insert Covenant Entry
            cursor.execute("""
                INSERT INTO replacement_covenants (id, redevelopment_project, original_hotel_id, units_demolished, replacement_units_covenanted, replacement_site_address, covenant_status)
                VALUES (?, ?, ?, ?, ?, ?, ?);
            """, (cov_id, RedevelopmentProject, OriginalHotelId, UnitsDemolished, ReplacementUnits, ReplacementSiteAddress, covenant_status))
            
            self.conn.commit()
            
            if rule_violation:
                return {
                    "status": "VIOLATION",
                    "covenant_id": cov_id,
                    "message": f"CRITICAL: 1:1 replacement rule violated for '{RedevelopmentProject}'! Demolished {UnitsDemolished} SRO units but only covenanted {ReplacementUnits} replacement units."
                }
            else:
                return {
                    "status": "APPROVED",
                    "covenant_id": cov_id,
                    "message": f"Certified: 1:1 replacement covenant validated for '{RedevelopmentProject}'. {UnitsDemolished} SRO units replaced."
                }
        except Exception as e:
            self.conn.rollback()
            return {"status": "FAILED", "message": f"Transaction rolled back: {e}"}

    def fetch_audit_summary(self):
        cursor = self.conn.cursor()
        cursor.execute("""
            SELECT c.id as covenant, c.redevelopment_project, h.name as original_hotel,
                   c.units_demolished, c.replacement_units_covenanted, c.covenant_status
            FROM replacement_covenants c
            JOIN sro_hotels h ON c.original_hotel_id = h.id;
        """)
        return [dict(row) for row in cursor.fetchall()]

