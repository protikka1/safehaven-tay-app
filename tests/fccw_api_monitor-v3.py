def main():
    print(TerminalColors.HEADER + TerminalColors.BOLD + "="*80)
    print("FOURTH & CENTRAL COMMUNITY WATCH (FCCW) - GIS API WATCHDOG SYSTEM (v3)")
    print("="*80 + TerminalColors.ENDC)

    # 1. Fetch active data
    raw_cases, data_source = LAPlanningAPIClient.fetch_active_cases()
    print(f"📂 Data Source: {TerminalColors.BOLD}{data_source}{TerminalColors.ENDC}")
    print(f"📊 Active Records Ingested: {len(raw_cases)}")
    print(TerminalColors.HEADER + "-"*80 + TerminalColors.ENDC)

    # 2. Process and Audit
    violations_count = 0
    warnings_count = 0
    passes_count = 0

    for idx, case in enumerate(raw_cases, 1):
        audit = GISZoningAuditor.audit_case(case)
        
        # Color coding severity outputs
        if audit["severity"] == "CRITICAL":
            color = TerminalColors.FAIL
            violations_count += 1
        elif audit["severity"] == "WARNING":
            color = TerminalColors.WARNING
            warnings_count += 1
        else:
            color = TerminalColors.OKGREEN
            passes_count += 1

        print(f"\n{TerminalColors.BOLD}[RECORD {idx}/{len(raw_cases)}] Case: {audit['case_number']}{TerminalColors.ENDC}")
        print(f"🏢 Project: {audit['project']}")
        print(f"📍 Address: {audit['address']}")
        print(f"🌍 Coordinates: Latitude: {audit['coordinates'][0]}, Longitude: {audit['coordinates'][1]}")
        print(f"   Location: {'Inside Skid Row' if audit['inside_skid_row'] else 'Surrounding Buffer Zone'}")
        print(f"📈 Affordability Rate: {audit['affordability_rate']}%")
        print(f"🚦 Audit Status: {color}{TerminalColors.BOLD}{audit['zoning_compliance']}{TerminalColors.ENDC}")

        if audit["warnings"]:
            print(TerminalColors.BOLD + "🚨 Warnings / Infractions Detected:" + TerminalColors.ENDC)
            for warning in audit["warnings"]:
                print(f"   {color}• {warning}{TerminalColors.ENDC}")
            
            # Dispatch mobile SMS text alert if infraction is found
            print()
            SMSAlertDispatcher.dispatch_alert(audit)
        else:
            print(TerminalColors.OKGREEN + "   ✓ Case meets localized inclusionary standards." + TerminalColors.ENDC)

    print("\n" + TerminalColors.HEADER + "="*80)
    print("                      MONITORING WORKSPACE STATUS SUMMARY")
    print("="*80 + TerminalColors.ENDC)
    print(f"  🟢 {TerminalColors.OKGREEN}PASSES:{TerminalColors.ENDC}             {passes_count}")
    print(f"  🟡 {TerminalColors.WARNING}WARNINGS/BUFFFERS:{TerminalColors.ENDC} {warnings_count}")
    print(f"  🔴 {TerminalColors.FAIL}VIOLATIONS:{TerminalColors.ENDC}        {violations_count}")
    
    if violations_count > 0:
        print(TerminalColors.FAIL + TerminalColors.BOLD + "\n[ALERT] Spatial boundaries have been breached! Automated email and SMS alerts dispatched." + TerminalColors.ENDC)
    else:
        print(TerminalColors.OKGREEN + TerminalColors.BOLD + "\n[SECURE] No unmitigated spatial boundary violations detected in this audit sequence." + TerminalColors.ENDC)
    print(TerminalColors.HEADER + "="*80 + TerminalColors.ENDC)

if __name__ == "__main__":
    main()
