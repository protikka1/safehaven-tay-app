class LAPlanningAPIClient:
    """
    Handles live querying of the LA Open Data Socrata API with dynamic 
    offline fallback routing.
    """
    @staticmethod
    def fetch_active_cases():
        print(f"📡 Querying Los Angeles City Planning Open Data API...")
        print(f"🔗 Target: {LA_PLANNING_API_URL}\n")
        
        try:
            req = urllib.request.Request(
                LA_PLANNING_API_URL, 
                headers={'User-Agent': 'FCCW-Watchdog-Client/1.0'}
            )
            with urllib.request.urlopen(req, timeout=3) as response:
                data = json.loads(response.read().decode('utf-8'))
                print(TerminalColors.OKGREEN + "✓ Live API connection successfully established!" + TerminalColors.ENDC)
                return data, "Live API"
                
        except (urllib.error.URLError, socket.timeout) as e:
            print(TerminalColors.WARNING + f"⚠️  Network Link Unavailable (Offline Sandbox Mode detected: {e})" + TerminalColors.ENDC)
            print(TerminalColors.OKCYAN + "➡ Redirecting data ingestion stream to High-Fidelity Local Cache..." + TerminalColors.ENDC)
            return MOCK_API_RESPONSE, "Local Cached Feed (Simulation Fallback)"

