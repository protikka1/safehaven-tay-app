class SMSAlertDispatcher:
    """
    Handles formatting and transmitting immediate SMS push notifications to
    community organizers when spatial or SRO covenants are breached.
    """
    @classmethod
    def dispatch_alert(cls, audit):
        """
        Formats and attempts transmission of REST SMS payload. Falls back to
        writing secure local simulation traces when network is unavailable.
        """
        severity = audit["zoning_compliance"]
        project = audit["project"]
        case_no = audit["case_number"]
        aff_rate = audit["affordability_rate"]
        warning_msg = audit["warnings"][0] if audit["warnings"] else "Localized review required."
        
        # Format a highly concise, immediate mobile text alert
        sms_text = (
            f"[FCCW WATCHDOG ALERT] {severity}!\n"
            f"Project: {project}\n"
            f"Case: {case_no}\n"
            f"Affordability: {aff_rate}%\n"
            f"Breach: {warning_msg}\n"
            f"Action Required: File appeal within 15 days."
        )

        print(f"📱 Preparing SMS text dispatch to {len(SMS_CONFIG['ORGANIZER_NUMBERS'])} mobile numbers...")
        
        # Twilio API Endpoint URL construction
        account_sid = SMS_CONFIG["TWILIO_ACCOUNT_SID"]
        auth_token = SMS_CONFIG["TWILIO_AUTH_TOKEN"]
        sender = SMS_CONFIG["TWILIO_SENDER_NUMBER"]
        twilio_url = f"https://api.twilio.com/2010-04-01/Accounts/{account_sid}/Messages.json"

        # Use a writable local outbox in desktop, mobile, and sandbox runtimes.
        scratch_dir = os.environ.get(
            "FCCW_OUTBOX_DIR",
            os.path.join(os.path.dirname(os.path.dirname(__file__)), "database", "outbox"),
        )
        try:
            os.makedirs(scratch_dir, exist_ok=True)
        except OSError:
            scratch_dir = os.path.join(tempfile.gettempdir(), "fccw-outbox")
            os.makedirs(scratch_dir, exist_ok=True)

        # Loop through each registered number
        for recipient in SMS_CONFIG["ORGANIZER_NUMBERS"]:
            payload = {
                "From": sender,
                "To": recipient,
                "Body": sms_text
            }
            
            encoded_payload = urllib.parse.urlencode(payload).encode("utf-8")
            
            try:
                # Setup Basic Auth header for Twilio API request
                req = urllib.request.Request(twilio_url, data=encoded_payload, method="POST")
                auth = base64.b64encode(
                    f"{account_sid}:{auth_token}".encode("utf-8")
                ).decode("ascii")
                req.add_header("Authorization", f"Basic {auth}")
                
                print(f"   🔗 Transmitting POST request to Twilio for {recipient}...")
                # 3-second timeout for fast-failing offline runtimes
                with urllib.request.urlopen(req, timeout=3):
                    print(TerminalColors.OKGREEN + f"   ✓ SMS successfully delivered to {recipient}!" + TerminalColors.ENDC)
                    
            except Exception as e:
                # Catch offline errors and write to local sandbox outbox for verification
                sms_filename = f"fccw_sms_alert_{case_no}_{recipient.replace('+', '')}.txt"
                sms_path = os.path.join(scratch_dir, sms_filename)
                
                with open(sms_path, "w") as f:
                    f.write(f"--- MOCK SMS OUTBOX DISPATCH ---\n")
                    f.write(f"Timestamp: {datetime.now().isoformat()}\n")
                    f.write(f"API URL: {twilio_url}\n")
                    f.write(f"Auth SID: {account_sid}\n")
                    f.write(f"Recipient: {recipient}\n")
                    f.write(f"Sender: {sender}\n")
                    f.write(f"Message:\n{sms_text}\n")
                    f.write(f"---------------------------------\n")
                
                print(TerminalColors.WARNING + f"   ⚠️  SMTP/REST Link Offline ({e})" + TerminalColors.ENDC)
                print(TerminalColors.OKCYAN + f"   ➡ Simulation trace written to local outbox: {sms_path}" + TerminalColors.ENDC)

        print(f"----------------------------------------")
        print(TerminalColors.OKGREEN + f"✓ Mobile alert simulation log updated." + TerminalColors.ENDC)
        print(f"----------------------------------------\n")

